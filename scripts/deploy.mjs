import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {createAccount,createClient} from 'genlayer-js';
import {studionet} from 'genlayer-js/chains';
import {finalized,stringify} from '../src/chain.js';
const key=process.env.SUPPORTGATE_PRIVATE_KEY;
if(!/^0x[0-9a-fA-F]{64}$/.test(key||''))throw new Error('Set SUPPORTGATE_PRIVATE_KEY to an authorized Studionet signing key. No account is generated automatically.');
const account=createAccount(key);const client=createClient({chain:studionet,account});
if(parseInt(await client.request({method:'eth_chainId'}),16)!==61999)throw new Error('Wrong chain');
const code=await readFile('contracts/supportgate.py','utf8');
await client.getContractSchemaForCode(code);
const hash=await client.deployContract({code,args:[],leaderOnly:false});
console.log('Deployment submitted:',hash);
await mkdir('artifacts',{recursive:true});await writeFile('artifacts/deploy-pending.json',stringify({hash,account:account.address}));
const tx=await finalized(client,hash,status=>console.log(status));
const address=tx.data?.contract_address||tx.to_address||tx.recipient;
if(!/^0x[0-9a-fA-F]{40}$/.test(address||'')||/^0x0{40}$/.test(address))throw new Error('No valid deployed address in receipt; inspect artifacts/deploy-pending.json and the explorer.');
const deployed=await client.getContractCode(address);
if(deployed!==code)throw new Error('Deployed code differs from local contract');
const config={chainId:61999,rpc:'https://studio.genlayer.com/api',address,deploymentTransaction:hash,verified:true,sourceSha256:createHash('sha256').update(code).digest('hex')};
await writeFile('public/deployment.json',stringify(config)+'\n');
await mkdir('evidence',{recursive:true});await writeFile('evidence/deployment.json',stringify({config,transaction:tx})+'\n');console.log('Verified contract:',address);
